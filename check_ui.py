    assert not errors, errors
    print({'status':'PASS','checks':['3 profiles','advisor entities','manual transactions','CSV import','persistence','goal editing','evidence','scenario','lesson feedback','filters','dark mode','5 viewport widths','reduced motion'],'page_errors':errors})
